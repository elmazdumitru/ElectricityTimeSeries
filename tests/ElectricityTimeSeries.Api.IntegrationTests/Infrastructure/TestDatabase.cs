using ElectricityTimeSeries.Infrastructure;
using Microsoft.Data.SqlClient;

namespace ElectricityTimeSeries.Api.IntegrationTests.Infrastructure;

/// <summary>Storage for one API at a time: in-memory, or a uniquely named SQL Server database.
/// Creating a SQL Server database takes seconds, so on dispose it is emptied and reused.</summary>
public sealed class TestDatabase : IAsyncDisposable
{
    private const string MigrationsHistoryTable = "__EFMigrationsHistory";

    private readonly TestStorage? _pool;
    private readonly string? _serverConnectionString;
    private readonly string? _name;

    private TestDatabase(StorageProvider provider, string? connectionString, TestStorage? pool, string? serverConnectionString, string? name)
    {
        Provider = provider;
        ConnectionString = connectionString;
        _pool = pool;
        _serverConnectionString = serverConnectionString;
        _name = name;
    }

    public StorageProvider Provider { get; }

    /// <summary><c>null</c> for in-memory storage.</summary>
    public string? ConnectionString { get; }

    public bool IsMigrated { get; private set; }

    /// <summary>A fresh in-memory store, with nothing to clean up afterwards.</summary>
    public static TestDatabase InMemory() => new(StorageProvider.InMemory, null, null, null, null);

    /// <summary>A uniquely named database that doesn't exist yet; <see cref="ApiFactory.PrepareAsync"/> creates it.</summary>
    public static TestDatabase OnSqlServer(string serverConnectionString, TestStorage pool)
    {
        var name = $"ets_{Guid.NewGuid():N}";
        var connectionString = new SqlConnectionStringBuilder(serverConnectionString) { InitialCatalog = name }.ConnectionString;
        return new TestDatabase(StorageProvider.SqlServer, connectionString, pool, serverConnectionString, name);
    }

    public void MarkMigrated() => IsMigrated = true;

    /// <summary>Empties a SQL Server database and returns it to the pool; drops it if that fails.</summary>
    public async ValueTask DisposeAsync()
    {
        if (_pool is null || ConnectionString is null)
        {
            return;
        }

        if (IsMigrated)
        {
            try
            {
                await EmptyAsync();
                _pool.GiveBack(this);
                return;
            }
            catch (SqlException)
            {
                // Fall through and drop it, so a broken database is never handed out again.
            }
        }

        await DropAsync();
    }

    /// <summary>Deletes all rows except the migrations history, with foreign key checks off meanwhile.</summary>
    private async Task EmptyAsync()
    {
        await using var connection = new SqlConnection(ConnectionString);
        await connection.OpenAsync();
        await using var empty = connection.CreateCommand();
        empty.CommandText = $"""
            DECLARE @tables TABLE (name nvarchar(300));
            INSERT INTO @tables
                SELECT QUOTENAME(SCHEMA_NAME(schema_id)) + N'.' + QUOTENAME(name)
                FROM sys.tables
                WHERE name <> N'{MigrationsHistoryTable}';

            DECLARE @sql nvarchar(max) = N'';
            SELECT @sql += N'ALTER TABLE ' + name + N' NOCHECK CONSTRAINT ALL; ' FROM @tables;
            SELECT @sql += N'DELETE FROM ' + name + N'; ' FROM @tables;
            SELECT @sql += N'ALTER TABLE ' + name + N' WITH CHECK CHECK CONSTRAINT ALL; ' FROM @tables;
            EXEC sp_executesql @sql;
            """;
        await empty.ExecuteNonQueryAsync();
    }

    private async Task DropAsync()
    {
        // Close pooled connections first. The name is generated by us, so it's safe to put in the SQL.
        await using (var connection = new SqlConnection(ConnectionString))
        {
            SqlConnection.ClearPool(connection);
        }

        await using var server = new SqlConnection(_serverConnectionString);
        await server.OpenAsync();
        await using var drop = server.CreateCommand();
        drop.CommandText = $"""
            IF DB_ID('{_name}') IS NOT NULL
            BEGIN
                ALTER DATABASE [{_name}] SET SINGLE_USER WITH ROLLBACK IMMEDIATE;
                DROP DATABASE [{_name}];
            END
            """;
        await drop.ExecuteNonQueryAsync();
    }
}
